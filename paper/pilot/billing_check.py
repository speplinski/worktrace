"""Reconcile the run logs with the providers' usage exports (post hoc check, 2026-11-03). Usage:
  python paper/pilot/billing_check.py <dir with the four CSV exports>
Expected files (console exports, not committed because they carry key and organisation identifiers):
  claude_api_tokens_*.csv, claude_api_cost_*.csv (Anthropic Console, Usage and Cost), completions_usage_*.csv and
  cost_*.csv (OpenAI dashboard). Writes paper/pilot/billing_check.md with per-model billed and logged token counts, the
  billed USD and the list-price cost of the billed tokens at the rates of token_costs.py. Usage of the judge files is
  attributed to the judges (Claude Haiku 5.5; GPT-6.1 Sol for A10); the Decisions API usage is logged but absent from
  OpenAI's completions export, and is billed at gpt-6-luna rates (the unexplained remainder of the OpenAI bill equals it)."""
import csv, glob, json, sys
from collections import Counter, defaultdict
from pathlib import Path
HERE = Path(__file__).resolve().parent; ROOT = HERE.parents[1]
sys.path.insert(0, str(ROOT))
RATES = {"claude-haiku-5-5": (0.10, 0.50, 0.01, 0.125), "claude-sonnet-5-5": (2.00, 10.00, 0.10, 2.50), "claude-opus-5-5": (4.00, 20.00, 0.20, 5.00),
         "gpt-6-luna": (0.10, 0.50, 0.01, 0.125), "gpt-6.1-terra": (1.00, 5.00, 0.05, 1.25), "gpt-6.1-sol": (2.00, 10.00, 0.10, 2.50)}
KEYS = ("input", "cache_write", "cache_read", "output")


def main(d: Path):
    billed, usd, days = defaultdict(Counter), Counter(), defaultdict(set)
    for f in glob.glob(str(d / "claude_api_tokens_*.csv")):
        for r in csv.DictReader(open(f)):
            m = r["model_version"]; days[m].add(r["usage_date_utc"])
            for k, kk in (("usage_input_tokens_no_cache", "input"), ("usage_input_tokens_cache_write_5m", "cache_write"), ("usage_input_tokens_cache_read", "cache_read"), ("usage_output_tokens", "output")):
                billed[m][kk] += int(r[k])
    for f in glob.glob(str(d / "claude_api_cost_*.csv")):
        for r in csv.DictReader(open(f)):
            if r["model"] != "--":
                usd[r["model"].lower().replace("claude ", "claude-").replace(" ", "-").replace(".", "-")] += float(r["cost_usd"])
    for f in glob.glob(str(d / "completions_usage_*.csv")):
        for r in csv.DictReader(open(f)):
            if r["model"]:
                days[r["model"]].add(r["start_time_iso"][:10])
                for k, kk in (("input_uncached_tokens", "input"), ("input_cache_write_tokens", "cache_write"), ("input_cached_tokens", "cache_read"), ("output_tokens", "output")):
                    billed[r["model"]][kk] += int(float(r[k]))
    openai_usd = 0.0
    for f in glob.glob(str(d / "cost_*.csv")):
        for r in csv.DictReader(open(f)):
            if r["amount_value"]:
                openai_usd += float(r["amount_value"])
    logged, src = defaultdict(Counter), defaultdict(set)
    for f in glob.glob(str(ROOT / "runs/**/*.jsonl"), recursive=True):
        rel = f.split("runs/")[1]
        for line in open(f):
            try:
                rec = json.loads(line)
            except Exception:
                continue
            us = rec.get("usage")
            if not us:
                continue
            if rel.startswith("judge/"):
                m = "claude-haiku-5-5"
            elif rel.startswith("judge_check/"):
                m = "gpt-6.1-sol"
            else:
                a = rec.get("agent", "")
                if not isinstance(a, str) or not a.startswith(("claude:", "openai")):
                    continue
                m = "decisions:gpt-6-luna" if a.startswith("openai-decisions") else a.split(":")[1]
            src[m].add(rel)
            for u in (us if isinstance(us, list) else [us]):
                if isinstance(u, dict):
                    for kk in KEYS:
                        logged[m][kk] += u.get(kk, 0) or 0
    L = ["# Billed usage against the run logs (post hoc check, 2026-11-03)", "",
         "Generated by `paper/pilot/billing_check.py` from the providers' usage exports (not in the repository) and `runs/`. Billed = the console export; "
         "logged = the `usage` fields of every record, judge files attributed to the judges. List price = billed tokens at the rates of `token_costs.py`. "
         "Anthropic usage 2026-10-25 to 2026-10-31 (pilot runs, smoke test, judge); OpenAI usage 2026-10-26 to 2026-10-27 (three agents, Decisions API, second judge).", "",
         "| model | days | tokens | billed | logged | logged / billed |", "|---|---|---|---:|---:|---:|"]
    for m in RATES:
        for kk in KEYS:
            b, l = billed[m][kk], logged[m][kk]
            L.append(f"| {m} | {min(days[m])}..{max(days[m])} | {kk} | {b:,} | {l:,} | {l / b if b else float('nan'):.4f} |")
    L += ["", "| model | billed USD | list price of billed tokens (USD) |", "|---|---:|---:|"]
    tot = 0.0
    for m, (ri, ro, rr, rw) in RATES.items():
        b = billed[m]; est = (b["input"] * ri + b["output"] * ro + b["cache_read"] * rr + b["cache_write"] * rw) / 1e6; tot += est
        L.append(f"| {m} | {usd.get(m, float('nan')):.2f} | {est:.2f} |" if m in usd else f"| {m} | (in the OpenAI total) | {est:.2f} |")
    dl = logged["decisions:gpt-6-luna"]; ri, ro, rr, rw = RATES["gpt-6-luna"]
    dec = (dl["input"] * ri + dl["output"] * ro + dl["cache_read"] * rr + dl["cache_write"] * rw) / 1e6
    L += [f"| Decisions API (gpt-6-luna rates; logged tokens, absent from the completions export) | (in the OpenAI total) | {dec:.2f} |",
          f"| Anthropic total | {sum(usd.values()):.2f} | {sum((billed[m]['input'] * r[0] + billed[m]['output'] * r[1] + billed[m]['cache_read'] * r[2] + billed[m]['cache_write'] * r[3]) / 1e6 for m, r in RATES.items() if m.startswith('claude')):.2f} |",
          f"| OpenAI total | {openai_usd:.2f} | {sum((billed[m]['input'] * r[0] + billed[m]['output'] * r[1] + billed[m]['cache_read'] * r[2] + billed[m]['cache_write'] * r[3]) / 1e6 for m, r in RATES.items() if m.startswith('gpt')) + dec:.2f} |",
          "", "Sources of the logged counts: " + "; ".join(f"{m}: {', '.join(sorted(v))}" for m, v in sorted(src.items())) + "."]
    (HERE / "billing_check.md").write_text("\n".join(L) + "\n"); print("written", HERE / "billing_check.md")


if __name__ == "__main__":
    main(Path(sys.argv[1]))
