"""Declared-grounds test (H2), mechanical version: the documents an agent declared as decisive are compared with the
decisive document(s) the generator defines for the episode, with no judge involved. Scored, like the judge's static
check, against the interventional basis label of the same decision (correct outcomes only; decisions with a judge
verdict, so that the populations coincide). Usage: python paper/pilot/declared_grounds_check.py
Writes paper/pilot/declared_grounds_check.md."""
from __future__ import annotations
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from worktrace import analysis as A
from worktrace import answer_key as K
from worktrace.answer_key import corrected

HERE = Path(__file__).resolve().parent
A.JUDGE.update(A.load_judgments("runs/judge"))


def rows_for(data, key):
    rows = []
    for cfg, recs in sorted(data.items()):
        for split in ("calibration",):
            for (cls, base, run), vs in A.units(recs, split).items():
                f = vs.get("factual")
                if f is None or not isinstance(f.get("decision"), dict) or A._act(f) not in f["astar"]:
                    continue
                j = A.JUDGE.get((f["agent"], split, f["episode_id"], run))
                if j is None:
                    continue
                arms = [v for n, v in vs.items() if n in A.INTERVENTIONS and not (key == "A1" and A.contested(v))]
                if not arms:
                    continue
                ifail = any(A._act(v) not in v["astar"] for v in arms)
                e = K.episode_of(f); dec = set(e.decisive); declared = set(f["decision"].get("decisive_sources") or [])
                rows.append({"cfg": cfg, "cls": cls, "ifail": ifail, "judge_static": not j["decisive_sources_correct"],
                             "judge_basis": not j["basis_sound"], "mech_exact": declared != dec, "mech_miss": not dec <= declared,
                             "mech_extra": not declared <= dec, "n_declared": len(declared), "n_dec": len(dec)})
    return rows


def rates(rows, flag):
    w = [r for r in rows if r["ifail"]]; ok = [r for r in rows if not r["ifail"]]
    sens = sum(r[flag] for r in w) / len(w) if w else float("nan"); fpr = sum(r[flag] for r in ok) / len(ok) if ok else float("nan")
    return sens, fpr, len(w), len(ok)


def main():
    full = A.load("runs/pilot"); core = {k: [r for r in v if A.in_core(r)] for k, v in full.items()}
    L = ["# Declared-grounds test (H2): judge's static check and a mechanical check against the generator's decisive document", "",
         "Generated by `paper/pilot/declared_grounds_check.py`. Population: correct-outcome calibration decisions of the judged configurations "
         "with a judge verdict; the interventional basis label is the reference. Flags: judge static = the judge's `decisive_sources_correct` is false; "
         "mechanical exact = the declared decisive set differs from the generator's decisive set; mechanical miss = a generator-decisive document is "
         "not declared; mechanical extra = a declared document is not generator-decisive. Sensitivity = flag rate among interventional basis failures; "
         "FPR = flag rate among decisions that pass every intervention; J = sensitivity − FPR.", ""]
    for dname, data in (("common core", core), ("all data", full)):
        for key in ("registered", "A1", "reviewed"):
            A.SENSITIVITY["on"] = key == "A1"
            d = corrected(data) if key == "reviewed" else data
            rows = rows_for(d, key); A.SENSITIVITY["on"] = False
            L += [f"## {dname}, {key} key", "", "| check | sensitivity | FPR | J | basis failures | pass all |", "|---|---|---|---|---|---|"]
            for flag, lab in (("judge_basis", "judge's basis verdict (the judge test)"), ("judge_static", "judge's static check of declared decisive sources"),
                              ("mech_exact", "mechanical: declared set ≠ generator's decisive set"), ("mech_miss", "mechanical: a decisive document not declared"),
                              ("mech_extra", "mechanical: a non-decisive document declared decisive")):
                s, f, nw, nok = rates(rows, flag)
                L.append(f"| {lab} | {s:.2f} | {f:.2f} | {s - f:+.2f} | {nw} | {nok} |")
            per = {}
            for r in rows:
                per.setdefault(r["cls"], []).append(r)
            L += ["", "Per class, mechanical exact (sensitivity / FPR): " + "; ".join(
                f"{c}: {rates(v, 'mech_exact')[0]:.2f} / {rates(v, 'mech_exact')[1]:.2f} (n {len(v)})" for c, v in sorted(per.items())), ""]
    (HERE / "declared_grounds_check.md").write_text("\n".join(L) + "\n"); print("\n".join(L[:20]))


if __name__ == "__main__":
    main()
