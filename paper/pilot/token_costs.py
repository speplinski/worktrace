"""Tokens and time per decision and per certified class, from the usage fields of the run logs (source for §7.3).

Per configuration, common core (run 0, first 60 calibration base episodes per class):
- factual decision: mean input-side tokens (input + cache read + cache write), mean output tokens (the API's output count, which for OpenAI already includes reasoning tokens),
  mean turns and mean wall-clock seconds of one factual calibration decision;
- certified class: total tokens of all calibration arms of one class (60 base episodes with their intervention and
  control arms), averaged over the three classes, and the ratio to the tokens of the 60 factual decisions alone.
USD is given for the Claude and OpenAI API configurations at the rates recorded in RATES below (Claude: e1_spec.md §11 and §13,
cached 2026-10-06, Sonnet cache read corrected to 0.10 on 2026-10-31; OpenAI: worktrace/score.py, read 2026-10-26; the Decisions API
at gpt-6-luna rates). The providers' usage exports confirm these rates: billed amounts and the logged tokens at these rates agree to
within USD 0.04 in total (paper/pilot/billing_check.md). Local models report tokens and seconds (author's MacBook). Usage: python paper/pilot/token_costs.py; writes token_costs.md.
"""
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, ".")
from worktrace import analysis as A

OUT = Path(__file__).resolve().parent / "token_costs.md"
# $/MTok: (input, output, cache read, cache write); e1_spec §11/§13, cached 2026-10-06; Sonnet cache read corrected to $0.10 (pricing page, 2026-10-31)
RATES = {"claude:claude-haiku-5-5:medium": (0.10, 0.50, 0.01, 0.125),
         "claude:claude-sonnet-5-5:medium": (2.00, 10.00, 0.10, 2.50),
         "claude:claude-opus-5-5:medium": (4.00, 20.00, 0.20, 5.00),
         # OpenAI, standard tier, as recorded in worktrace/score.py (developers.openai.com/api/docs/pricing, read 2026-10-26);
         # cached input at the cache rate, cache writes at 1.25 x the input price (default retention), as in score.py. Added 2026-11-03.
         # The Decisions API configuration is billed at gpt-6-luna rates: the remainder of the OpenAI bill not covered by the completions
         # export equals its logged tokens at these rates (paper/pilot/billing_check.md).
         "openai-decisions:gpt-6-luna": (0.10, 0.50, 0.01, 0.125),
         "openai:gpt-6-luna:medium": (0.10, 0.50, 0.01, 0.125),
         "openai:gpt-6.1-terra:medium": (1.00, 5.00, 0.05, 1.25),
         "openai:gpt-6.1-sol:medium": (2.00, 10.00, 0.10, 2.50)}


def tokens(r):
    i = o = cr = cw = 0
    for u in r.get("usage") or []:
        if isinstance(u, dict):
            i += u.get("input", 0) or 0; o += u.get("output", 0) or 0  # OpenAI's output_tokens already include reasoning tokens (output_tokens_details.reasoning_tokens is a subset); not added again (corrected 2026-11-03)
            cr += u.get("cache_read", 0) or 0; cw += u.get("cache_write", 0) or 0
    return i, o, cr, cw


def usd(cfg, i, o, cr, cw):
    if cfg not in RATES:
        return None
    ri, ro, rr, rw = RATES[cfg]
    return (i * ri + o * ro + cr * rr + cw * rw) / 1e6


def main():
    full = A.load("runs/pilot")
    lines = ["# Tokens and time per decision and per certified class (common core)", "",
             "Generated by `paper/pilot/token_costs.py` from the usage fields of `runs/pilot`. Input-side tokens = input + cache read + cache write; "
             "output tokens are the API's output counts, which for the OpenAI models already include reasoning tokens (reasoning_tokens is a subset of output_tokens; an earlier version of this script added them a second time, corrected 2026-11-03). USD for the Claude and OpenAI API configurations, at the list prices recorded "
             "in `e1_spec.md` (cached 2026-10-06; verify before use). A certified class = the 60 calibration base episodes of one class with all their "
             "arms; the ratio compares it with the 60 factual decisions of the same class.", "",
             "| configuration | factual decision: tokens in / out | turns | seconds | USD per factual decision | certified class: tokens in / out (arms per episode) | ratio to factual | USD per certified class |",
             "|---|---|---|---|---|---|---|---|"]
    for cfg, recs in sorted(full.items()):
        core = [r for r in recs if A.in_core(r) and r["split"] == "calibration"]
        fact = [r for r in core if r["variant"] == "factual"]
        if not fact:
            continue
        fi = sum(tokens(r)[0] + tokens(r)[2] + tokens(r)[3] for r in fact) / len(fact)
        fo = sum(tokens(r)[1] for r in fact) / len(fact)
        turns = sum(len(r.get("usage") or []) for r in fact) / len(fact)
        secs = sum(r.get("seconds") or 0 for r in fact) / len(fact)
        fu = [usd(cfg, *tokens(r)) for r in fact]
        fusd = (sum(fu) / len(fu)) if fu[0] is not None else None
        # per class: all arms
        by = defaultdict(lambda: [0, 0, 0, 0, 0, 0.0])   # in, out, records, factual records, factual in+out, usd
        for r in core:
            i, o, cr, cw = tokens(r); b = by[r["cls"]]
            b[0] += i + cr + cw; b[1] += o; b[2] += 1
            if r["variant"] == "factual":
                b[3] += 1; b[4] += i + cr + cw + o
            u = usd(cfg, i, o, cr, cw); b[5] += u or 0.0
        cls_in = sum(b[0] for b in by.values()) / len(by); cls_out = sum(b[1] for b in by.values()) / len(by)
        arms = sum(b[2] / max(1, b[3]) for b in by.values()) / len(by)
        ratio = sum((b[0] + b[1]) / max(1, b[4]) for b in by.values()) / len(by)
        cusd = (sum(b[5] for b in by.values()) / len(by)) if cfg in RATES else None
        lines.append(f"| {cfg} | {fi:,.0f} / {fo:,.0f} | {turns:.1f} | {secs:.1f} | {'–' if fusd is None else format(fusd, '.4f')} | "
                     f"{cls_in:,.0f} / {cls_out:,.0f} ({arms:.1f}) | {ratio:.1f}× | {'–' if cusd is None else format(cusd, '.2f')} |")
    OUT.write_text("\n".join(lines) + "\n")
    print(OUT)


if __name__ == "__main__":
    main()
