"""Decision models: calibration of the reported confidence (expected calibration error, Brier score) and the deferral
trade-off of a confidence threshold (share of decisions sent to a human vs share of unjustified decisions caught).
Common core, calibration split, factual decisions; unjustified = wrong outcome or basis failure (registered key; the
reviewed key is reported as a second column). Usage: python paper/pilot/confidence_calibration.py → confidence_calibration.md"""
from __future__ import annotations
import math, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from worktrace import analysis as A
from worktrace.answer_key import corrected

HERE = Path(__file__).resolve().parent
NAMES = {"basal:basal-2.0-max": "Basal 2.0-max", "systemone:d1": "Liquid AI d1-3B", "openai-decisions:gpt-6-luna": "GPT-6 Luna (Decisions API)"}


def rows_for(recs):
    out = []
    for (cls, base, run), vs in A.units(recs, "calibration").items():
        f = vs.get("factual")
        if not f or f.get("confidence") is None:
            continue
        correct = A._act(f) in f["astar"]
        basis_fail = any(A._act(v) not in v["astar"] for n, v in vs.items() if n in A.INTERVENTIONS)
        probs = f.get("probabilities"); act = A._act(f); p_act = None
        if isinstance(probs, dict):
            p_act = probs.get(act)
        elif isinstance(probs, list):
            p_act = next((x.get("probability") for x in probs if x.get("value") == act), None)
        out.append({"cls": cls, "conf": float(f["confidence"]), "p_act": None if p_act is None else float(p_act),
                    "correct": correct, "unjustified": (not correct) or basis_fail})
    return out


def ece_ci(rows, B=1000, seed=1):
    import random
    rng = random.Random(seed); vals = []
    for _ in range(B):
        samp = [rng.choice(rows) for _ in rows]; vals.append(ece(samp)[0])
    vals.sort(); return vals[int(0.025 * B)], vals[int(0.975 * B)]


def ece(rows, bins=10):
    tot = len(rows); e = 0.0; table = []
    for b in range(bins):
        lo, hi = b / bins, (b + 1) / bins
        sel = [r for r in rows if (lo <= r["conf"] < hi) or (b == bins - 1 and r["conf"] == 1.0)]
        if sel:
            acc = sum(r["correct"] for r in sel) / len(sel); conf = sum(r["conf"] for r in sel) / len(sel)
            e += len(sel) / tot * abs(acc - conf); table.append((lo, hi, len(sel), conf, acc))
    return e, table


def brier(rows):
    return sum((r["conf"] - r["correct"]) ** 2 for r in rows) / len(rows)


def deferral(rows, shares=(0.0, 0.1, 0.25, 0.5)):
    """Defer the share of decisions with the lowest confidence; report the unjustified rate among the rest and the share
    of all unjustified decisions caught by the deferral."""
    srt = sorted(rows, key=lambda r: r["conf"]); n = len(srt); n_unj = sum(r["unjustified"] for r in srt)
    out = []
    for s in shares:
        k = int(round(s * n)); kept, deferred = srt[k:], srt[:k]
        rate = sum(r["unjustified"] for r in kept) / len(kept) if kept else float("nan")
        caught = sum(r["unjustified"] for r in deferred) / n_unj if n_unj else float("nan")
        thr = srt[k]["conf"] if k < n else 1.0
        out.append((s, thr, rate, caught))
    return out, n, n_unj


def main():
    full = A.load("runs/pilot"); core = {k: [r for r in v if A.in_core(r)] for k, v in full.items()}
    L = ["# Decision models: confidence calibration and the deferral trade-off (common core, calibration split)", "",
         "Generated by `paper/pilot/confidence_calibration.py`. ECE = expected calibration error of the reported confidence against outcome correctness "
         "(10 equal-width bins); Brier = mean squared error of the confidence as a probability of a correct outcome. Deferral: the share of factual "
         "decisions with the lowest confidence is sent to a human; the unjustified rate is measured among the rest (wrong outcome or basis failure, "
         "registered key; reviewed key in the second block), and 'caught' is the share of all unjustified decisions among the deferred ones. The confidence field is what each model reports as its "
         "confidence; Basal's equals the probability of the chosen action, Liquid d1's and Luna's are below it, so an ECE on the probability of the chosen action is given as well.", ""]
    for key in ("registered", "reviewed"):
        data = corrected(core) if key == "reviewed" else core
        L += [f"## {key} key", ""]
        for cfg in NAMES:
            rows = rows_for(data[cfg])
            if not rows:
                continue
            e, table = ece(rows); b = brier(rows); lo, hi = ece_ci(rows)
            acc = sum(r["correct"] for r in rows) / len(rows); mconf = sum(r["conf"] for r in rows) / len(rows)
            pa = [dict(r, conf=r["p_act"]) for r in rows if r["p_act"] is not None]
            e_pa = ece(pa)[0] if pa else float("nan")
            L += [f"### {NAMES[cfg]} (n = {len(rows)}; mean confidence {mconf:.2f}, outcome accuracy {acc:.2f}; ECE {e:.3f}, 95% bootstrap interval [{lo:.3f}, {hi:.3f}]; "
                  f"Brier {b:.3f}; ECE using the reported probability of the chosen action instead of the confidence field: {e_pa:.3f})", "",
                  "| confidence bin | n | mean confidence | accuracy |", "|---|---|---|---|"]
            L += [f"| [{lo:.1f}, {hi:.1f}) | {n} | {c:.2f} | {a:.2f} |" for lo, hi, n, c, a in table]
            d, n, n_unj = deferral(rows)
            L += ["", f"Deferral trade-off (unjustified decisions: {n_unj} of {n}):", "",
                  "| deferred share | confidence threshold | unjustified rate among autonomous | share of unjustified caught |", "|---|---|---|---|"]
            L += [f"| {s:.0%} | {thr:.2f} | {rate:.1%} | {caught:.1%} |" for s, thr, rate, caught in d]
            per = {}
            for r in rows:
                per.setdefault(r["cls"], []).append(r)
            L += ["", "Per class, ECE / mean confidence / accuracy: " + "; ".join(
                f"{c}: {ece(v)[0]:.3f} / {sum(r['conf'] for r in v)/len(v):.2f} / {sum(r['correct'] for r in v)/len(v):.2f}" for c, v in sorted(per.items())), ""]
    (HERE / "confidence_calibration.md").write_text("\n".join(L) + "\n"); print("\n".join(L))


if __name__ == "__main__":
    main()
