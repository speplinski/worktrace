"""Appendix table: the measures registered in §5.4 that §6 does not report, per configuration and class, from
paper/pilot/results_core.md (registered key, common core) and results_interim.md (all data, for the Haiku majority vote and
protocol incidents). Usage: python paper/pilot/appendix_measures.py  → writes paper/pilot/appendix_measures.md"""
from __future__ import annotations
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
NAMES = {"basal:basal-2.0-max": "Basal 2.0-max", "claude:claude-haiku-5-5:medium": "Claude Haiku 5.5", "claude:claude-opus-5-5:medium": "Claude Opus 5.5",
         "claude:claude-sonnet-5-5:medium": "Claude Sonnet 5.5", "ollama-inline:SpeakLeash/bielik-11b-v3.0-instruct:Q8_0:seed7": "Bielik 11B v3 (one-pass)",
         "ollama:gemma4:26b:seed7:default": "Gemma 4 26B", "ollama:gpt-oss:120b:seed7:default": "gpt-oss 120B", "ollama:mistral-small3.2:24b:seed7:default": "Mistral Small 3.2",
         "ollama:qwen3.8:27b:seed7:default": "Qwen 3.8 27B", "openai-decisions:gpt-6-luna": "GPT-6 Luna (Decisions API)", "openai:gpt-6-luna:medium": "GPT-6 Luna",
         "openai:gpt-6.1-sol:medium": "GPT-6.1 Sol", "openai:gpt-6.1-terra:medium": "GPT-6.1 Terra", "systemone:d1": "Liquid AI d1-3B"}
CLS = {"c3": "discrepancy", "c5": "freshness", "c6": "onboarding"}


def blocks(path):
    t = path.read_text(); first = re.split(r"^# ", t, flags=re.M)[1]
    out = {}
    for m in re.finditer(r"^## (?!H3|Procedure)(.*?)\n(.*?)(?=^## |\Z)", first, flags=re.S | re.M):
        out[m.group(1).strip()] = m.group(2)
    return out


def main():
    core = blocks(HERE / "results_core.md"); alld = blocks(HERE / "results_interim.md")
    L = ["| configuration | class | cal. ℓ_out | cal. ℓ_WT | held-out ℓ_out / ℓ_WT | shifted ℓ_out | null flip | placebo, sham flip | non-react. | over-esc. | under-esc. |",
         "|---|---|---|---|---|---|---|---|---|---|---|"]
    notes = []
    for cfg, body in core.items():
        name = NAMES.get(cfg, cfg)
        fm = re.search(r"Further measures.*", body); fm = fm.group(0) if fm else ""
        for row in re.findall(r"^\| (c[356]) \| (\d+) \| (.*?) \|$", body, flags=re.M):
            cls, n, rest = row; cells = [c.strip() for c in rest.split("|")]
            # cells: ℓ_out, ℓ_basis, ℓ_WT, rowb, interv acc, null, placebo/sham, copy, oop, heldout, shifted
            l_out, l_basis, l_wt, rowb, acc, null, plc, copy, oop, held, shifted = cells[:11]
            m = re.search(rf"{cls}: non-reaction ([^,]+), over-escalation ([^,]+), under-escalation ([^;]+)", fm)
            nr, oe, ue = (x.strip().split(" (")[0] for x in m.groups()) if m else ("–", "–", "–")
            L.append(f"| {name} | {CLS[cls]} | {l_out} | {l_wt} | {held} | {shifted.split(' (')[0]} | {null} | {plc} | {nr} | {oe} | {ue} |")
        inc = re.search(r"Protocol incidents \(all splits\): (.*)", alld.get(cfg, body))
        if inc and not inc.group(1).startswith("none"):
            notes.append(f"- {name}: {inc.group(1)}")
        rb = re.search(r"Robustness \(§7\): (.*)", body)
        if rb:
            notes.append(f"- {name}, decisions recovered from text excluded: {rb.group(1)}")
        mv = re.search(r"Majority vote over runs.*?: (.*)", alld.get(cfg, ""))
        if mv:
            notes.append(f"- {name}, majority vote over the three runs (all data): {mv.group(1)}")
            mh = re.search(r"Majority vote, H3: (.*)", alld.get(cfg, ""))
            if mh:
                notes.append(f"- {name}, majority vote, delegation test: {mh.group(1)}")
    (HERE / "appendix_measures.md").write_text("# Measures registered in §5.4, per configuration and class (common core, registered key)\n\n"
                                               "Generated by `paper/pilot/appendix_measures.py` from `results_core.md` (and `results_interim.md` for the all-data notes).\n\n"
                                               + "\n".join(L) + "\n\nNotes:\n\n" + "\n".join(notes) + "\n")
    print("\n".join(L[:6])); print("...notes:"); print("\n".join(notes))


if __name__ == "__main__":
    main()
